"""Byte-equivalent fast path for repetitive opaque CAD LINE strokes.

The authoritative ezdxf drawing frontend is unchanged. Its native PyMuPDF
backend spends significant Python time in Shape.finish() for each of thousands
of ordinary lines produced by repeated INSERTs. For safe opaque strokes only,
this backend caches the exact PDF finish operator sequence generated by the
installed PyMuPDF. A one-line probe checks byte equality with Shape.finish()
for every new stroke style; unsupported PyMuPDF internals fall back to stock.

Do not batch strokes into one paint operation: that changes antialiasing at
intersections and fails exact-pixel regression on the user's real drawing.
"""
from __future__ import annotations

from ezdxf.addons.drawing import pymupdf


class _ExactLineBackend(pymupdf.PyMuPdfRenderBackend):
    def __init__(self, page, settings):
        super().__init__(page, settings)
        self._stroke_styles: dict[tuple, tuple[str, str] | None] = {}
        self.fast_line_count = 0
        self.fast_path_count = 0
        # Accumulate adjacent PDF paint operations as a list. Each operation
        # remains independent (unlike path batching), preserving overlapping
        # strokes and their exact antialiasing behavior.
        self._line_chunks: list[str] = []

    def _flush_lines(self):
        if self._line_chunks:
            self.content_shape.totalcont += ''.join(self._line_chunks)
            self._line_chunks.clear()

    def _exact_style(self, properties):
        key = (properties.color, properties.lineweight, properties.layer)
        if key in self._stroke_styles:
            return self._stroke_styles[key]
        self._stroke_styles[key] = None
        color = properties.color
        if not isinstance(color, str) or not (
                len(color) == 7 or (len(color) == 9 and color[-2:].lower() == 'ff')):
            return None
        shape = self.content_shape
        # These fields and formatting functions belong to PyMuPDF's Shape
        # implementation. Always validate generated bytes at runtime and fall
        # back if an installed version differs from the tested contract.
        if not isinstance(getattr(shape, 'totalcont', None), str):
            return None
        if not isinstance(getattr(shape, 'draw_cont', None), str):
            return None
        finish = getattr(type(shape), 'finish', None)
        glob = getattr(finish, '__globals__', {})
        formatter = glob.get('_format_g')
        color_code = glob.get('ColorCode')
        if not callable(formatter) or not callable(color_code):
            return None
        try:
            stroke = self.resolve_color(color)
            width = self.resolve_stroke_width(properties.lineweight)
            oc = self.get_optional_content_group(properties.layer)
            resource = self.page._get_optional_content(oc)
            opt_start = f'/OC /{resource} BDC\n' if resource is not None else ''
            opt_end = 'EMC\n' if resource is not None else ''
            pre = '\nq\n1 j\n1 J\n' + opt_start
            post = (formatter(width) + ' w\n' if width not in (0, 1) else '')
            post += color_code(stroke, 'c') + 'S\n' + opt_end + 'Q\n'
            # Validate against stock PyMuPDF on this very page, with identical
            # color, width, OCG and cap/join settings, without committing probe.
            probe = self.page.new_shape()
            probe.draw_line((0, 0), (1, 1))
            probe_commands = probe.draw_cont
            probe.finish(width=width, color=stroke, fill=None,
                         lineJoin=1, lineCap=1,
                         stroke_opacity=1.0, closePath=False, oc=oc)
            if probe.totalcont != pre + probe_commands + post:
                return None
        except (AttributeError, TypeError, ValueError, RuntimeError, KeyError):
            return None
        self._stroke_styles[key] = pre, post
        return pre, post

    def draw_line(self, start, end, properties):
        style = self._exact_style(properties)
        if style is None:
            self._flush_lines()
            return super().draw_line(start, end, properties)
        shape = self.content_shape
        shape.draw_line(start, end)
        self._line_chunks.append(style[0] + shape.draw_cont + style[1])
        # Limit temporary Python chunk references for very large drawings.
        # Each flush retains the same sequence of individual PDF operations.
        if len(self._line_chunks) >= 16384:
            self._flush_lines()
        shape.draw_cont = ''
        shape.last_point = None
        self.fast_line_count += 1


    # Flush before any non-LINE paint call to keep the original draw order.
    def draw_path(self, path, properties):
        # The ezdxf frontend expands repeated CIRCLE/ARC blocks into native
        # Bezier paths. Preserve *each* path and its separate stroke operation
        # (batched paths change intersection anti-aliasing). Only reuse the
        # byte-validated opaque style prologue/epilogue; filled/transparent
        # or unknown rendering styles fall back to PyMuPDF's stock finish().
        if len(path) == 0:
            return
        style = self._exact_style(properties)
        if style is None:
            self._flush_lines()
            return super().draw_path(path, properties)
        shape = self.content_shape
        pymupdf.add_path_to_shape(shape, path, close=False)
        self._line_chunks.append(style[0] + shape.draw_cont + style[1])
        if len(self._line_chunks) >= 16384:
            self._flush_lines()
        shape.draw_cont = ''
        shape.last_point = None
        self.fast_path_count += 1

    def draw_filled_paths(self, *args, **kwargs):
        self._flush_lines()
        return super().draw_filled_paths(*args, **kwargs)

    def draw_filled_polygon(self, *args, **kwargs):
        self._flush_lines()
        return super().draw_filled_polygon(*args, **kwargs)

    def draw_solid_lines(self, *args, **kwargs):
        self._flush_lines()
        return super().draw_solid_lines(*args, **kwargs)

    def draw_point(self, *args, **kwargs):
        self._flush_lines()
        return super().draw_point(*args, **kwargs)

    def draw_image(self, *args, **kwargs):
        self._flush_lines()
        return super().draw_image(*args, **kwargs)

    def set_background(self, *args, **kwargs):
        self._flush_lines()
        return super().set_background(*args, **kwargs)

    def finalize(self):
        self._flush_lines()
        return super().finalize()


class FastPyMuPdfBackend(pymupdf.PyMuPdfBackend):
    @staticmethod
    def make_backend(page, settings):
        return _ExactLineBackend(page, settings)
